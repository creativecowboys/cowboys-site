#!/usr/bin/env node
/**
 * Turns src/content/city-pages/*.json into routes.
 *   - writes src/content/city-pages/index.ts (static imports, so Next bundles them)
 *   - writes src/app/web-design-<slug>/page.tsx for every page
 *   - removes generated route folders whose JSON is gone
 * Run: node scripts/city-pages/generate.mjs
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const CONTENT = path.join(ROOT, "src/content/city-pages");
const APP = path.join(ROOT, "src/app");
const MARKER = "// GENERATED by scripts/city-pages/generate.mjs";

const files = fs.readdirSync(CONTENT).filter((f) => f.endsWith(".json")).sort();
const pages = files.map((f) => ({ file: f, data: JSON.parse(fs.readFileSync(path.join(CONTENT, f), "utf8")) }));
const ident = (slug) => "c_" + slug.replace(/[^a-z0-9]/g, "_");

const index = [
  "// AUTO-GENERATED by scripts/city-pages/generate.mjs. Do not edit by hand.",
  'import type { CityPage } from "@/lib/city-pages/types";',
  ...pages.map(({ file, data }) => `import ${ident(data.slug)} from "./${file}";`),
  "",
  "export const CITY_PAGES: CityPage[] = [",
  ...pages.map(({ data }) => `  ${ident(data.slug)} as CityPage,`),
  "];",
  "",
].join("\n");
fs.writeFileSync(path.join(CONTENT, "index.ts"), index);

const wanted = new Set();
for (const { data } of pages) {
  const dir = path.join(APP, data.path.replace(/^\//, ""));
  wanted.add(dir);
  const file = path.join(dir, "page.tsx");
  if (fs.existsSync(file) && !fs.readFileSync(file, "utf8").startsWith(MARKER)) {
    console.error(`Refusing to overwrite hand-built route ${data.path}`);
    process.exit(1);
  }
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    file,
    `${MARKER} from src/content/city-pages/${data.slug}.json
import CityLandingPage from "@/components/city/CityLandingPage";
import { cityPageMetadata, getCityPage } from "@/lib/city-pages";

const page = getCityPage(${JSON.stringify(data.slug)});

export const metadata = cityPageMetadata(page);

export default function Page() {
  return <CityLandingPage page={page} />;
}
`,
  );
}

// Clean up generated routes whose content was removed.
for (const name of fs.readdirSync(APP)) {
  const dir = path.join(APP, name);
  const file = path.join(dir, "page.tsx");
  if (!name.startsWith("web-design-") || wanted.has(dir) || !fs.existsSync(file)) continue;
  if (fs.readFileSync(file, "utf8").startsWith(MARKER)) {
    fs.rmSync(dir, { recursive: true });
    console.log(`removed ${name}`);
  }
}
console.log(`${pages.length} city pages generated`);
